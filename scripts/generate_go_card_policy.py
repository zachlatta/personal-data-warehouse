"""Generate the Go mirror of the shared issuer policy; --check verifies parity."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    data=json.loads((ROOT/'src/personal_data_warehouse/card_policy.json').read_text())
    payload=json.dumps(data,separators=(',',':'))
    output='// Code generated by scripts/generate_go_card_policy.py; DO NOT EDIT.\npackage cardpolicy\n\nconst JSON = `'+payload+'`\n'
    path=ROOT/'app/internal/cardpolicy/policy_gen.go'
    if args.check:
        if not path.exists() or path.read_text()!=output:raise SystemExit('Go card policy is stale')
    else:
        path.parent.mkdir(exist_ok=True);path.write_text(output)


if __name__=='__main__':main()
