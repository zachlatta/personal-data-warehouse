// Every PDW alert on Android is drawn by the app, so the app can make room under
// Android's 50-notification limit before each one.
//
// Chat alerts (a message, a WhatsApp, a Slack DM) are drawn the way Android draws
// a messaging app's: NotificationCompat.MessagingStyle with the sender as a
// Person (contact photo or an initial), one notification per chat that stacks
// its messages, a long-lived conversation shortcut so it sits in the shade's
// Conversations section, on a "Messages" channel. Every other alert is a title,
// text and optional picture on the "default" channel.
//
// An Expo push with a title arrives as an FCM notification message that Android
// draws itself while the app is in the background, without running app code. So
// the server sends every alert as a data-only push (app/internal/push and
// app/internal/notifications/sender.go, only to a device that registered the
// android_native_alerts capability, see app.json extra.pushCapabilities), and
// this plugin replaces expo-notifications' FCM service with a subclass that draws
// a push carrying `android_style` or `android_alert` and hands anything else to
// Expo unchanged. A tap goes through Expo's own response intent, so src/lib/push.ts
// handles it exactly like any other alert.
