// Every PDW alert on Android is drawn by the app, so the app can make room under
// Android's 50-notification limit before each one and render every source like
// its native Android app.
//
// Chat alerts (Messages, WhatsApp, Slack) are drawn with
// NotificationCompat.MessagingStyle: sender Person with circular contact face
// (or Material monogram), inline image attachments via FileProvider, stacked
// conversation history, long-lived conversation shortcut for Android 11+'s
// Conversations section, per-source channel and accent color, real event
// timestamps, and per-source grouping.
//
// Non-chat alerts (Gmail, Calendar, Google Drive, Scans, Approvals, notify)
// are drawn with circular sender faces (or monograms), bold subject + snippet
// BigTextStyle for email, BigPictureStyle for real content images, per-source
// channels, categories, accent colors, real event timestamps, and InboxStyle
// group summaries when multiple alerts from the same source are active.
//
// An Expo push with a title arrives as an FCM notification message that Android
// draws itself while the app is in the background, without running app code. So
// the server sends every alert as a data-only push (app/internal/push and
// app/internal/notifications/sender.go, only to a device that registered the
// android_native_alerts capability, see app.json extra.pushCapabilities), and
// this plugin replaces expo-notifications' FCM service with a subclass that draws
// a push carrying `android_style` or `android_alert` and hands anything else to
// Expo unchanged. A tap goes through Expo's own response intent, so src/lib/push.ts
// handles it exactly like any other alert.
