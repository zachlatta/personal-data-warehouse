// The Pixel Launcher's left page (swipe right on the first home page; stock:
// Google Discover) shows the PDW Feed. Pixel Launcher 17 embeds an activity
// that handles com.android.launcher3.WINDOW_OVERLAY from the package its
// `supported_overlay_apps` array names, in a task fragment inside its own task,
// and drives the swipe in and out itself. On Zach's phone a static overlay
// (sysadmin repo, pichu/2026-10-25-pdw-left-screen.md) sets that array to this
// app. This plugin adds the activity: a second React surface rendering the
// `leftscreen` component (src/features/feed/left-screen.tsx).
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const ACTIVITY = '.LeftScreenActivity';

const KOTLIN = (pkg) => `package ${pkg}

import android.content.Intent
import android.os.Bundle

import com.facebook.react.ReactActivity
import com.facebook.react.ReactActivityDelegate
import com.facebook.react.defaults.DefaultNewArchitectureEntryPoint.fabricEnabled
import com.facebook.react.defaults.DefaultReactActivityDelegate
import com.facebook.react.modules.core.DeviceEventManagerModule

import expo.modules.ReactActivityDelegateWrapper

/**
 * The launcher's left page (generated by plugins/with-left-screen.js). The
 * launcher keeps this activity in a task fragment and slides it in and out, so
 * it must stay the fragment's only activity: anything it opens (a card in the
 * app, a browser, a share) starts in its own task.
 */
class LeftScreenActivity : ReactActivity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(null)
  }

  override fun getMainComponentName(): String = "leftscreen"

  override fun createReactActivityDelegate(): ReactActivityDelegate {
    return ReactActivityDelegateWrapper(
          this,
          BuildConfig.IS_NEW_ARCHITECTURE_ENABLED,
          object : DefaultReactActivityDelegate(
              this,
              mainComponentName,
              fabricEnabled
          ){})
  }

  // Sent before the app-wide AppState change, so the Feed tab and the left
  // page agree on which one Zach is looking at.
  override fun onResume() {
    emitVisible(true)
    super.onResume()
  }

  override fun onPause() {
    emitVisible(false)
    super.onPause()
  }

  private fun emitVisible(visible: Boolean) {
    reactHost?.currentReactContext
      ?.getJSModule(DeviceEventManagerModule.RCTDeviceEventEmitter::class.java)
      ?.emit("pdwLeftScreenVisible", visible)
  }

  override fun startActivityForResult(intent: Intent, requestCode: Int, options: Bundle?) {
    intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    super.startActivityForResult(intent, requestCode, options)
  }
}
`;

function withLeftScreenManifest(config) {
  return withAndroidManifest(config, (config) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    app.activity = (app.activity ?? []).filter((a) => a.$['android:name'] !== ACTIVITY);
    app.activity.push({
      $: {
        'android:name': ACTIVITY,
        'android:exported': 'true',
        'android:excludeFromRecents': 'true',
        'android:taskAffinity': '',
        'android:allowUntrustedActivityEmbedding': 'true',
        'android:configChanges': 'keyboard|keyboardHidden|orientation|screenSize|screenLayout|uiMode|smallestScreenSize|assetsPaths',
        'android:windowSoftInputMode': 'adjustResize',
        'android:screenOrientation': 'portrait',
        'android:theme': '@style/AppTheme',
      },
      'intent-filter': [
        {
          action: [{ $: { 'android:name': 'com.android.launcher3.WINDOW_OVERLAY' } }],
          category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
        },
      ],
    });
    return config;
  });
}

function withLeftScreenActivity(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const pkg = config.android?.package;
      if (!pkg) throw new Error('with-left-screen: android.package is not set');
      const dir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, 'LeftScreenActivity.kt'), KOTLIN(pkg));
      return config;
    },
  ]);
}

module.exports = function withLeftScreen(config) {
  return withLeftScreenActivity(withLeftScreenManifest(config));
};
